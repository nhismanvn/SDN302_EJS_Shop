require('dotenv').config();
const express = require('express');
const mongoose = require('mongoose');
const session = require('express-session');
const MongoStore = require('connect-mongo');
const path = require('path');
const app = express();
app.set('view engine','ejs');
app.set('views',path.join(__dirname,'views'));
app.use(express.urlencoded({extended:false}));
app.use(express.static(path.join(__dirname,'public')));
app.set('trust proxy', 1);
if (!process.env.MONGODB_URI || !process.env.SESSION_SECRET) throw new Error('Set MONGODB_URI and SESSION_SECRET in .env');
app.use(session({name:'shop.sid',secret:process.env.SESSION_SECRET,resave:false,saveUninitialized:false,store:MongoStore.create({mongoUrl:process.env.MONGODB_URI}),cookie:{httpOnly:true,sameSite:'lax',secure:process.env.NODE_ENV === 'production',maxAge:1000*60*60*2}}));
app.use((req,res,next)=>{res.locals.user=req.session.user || null;next();});
app.use('/',require('./routes/authRoutes'));
app.use('/',require('./routes/orderRoutes'));
app.use((req,res)=>res.status(404).send('Page not found'));
mongoose.connect(process.env.MONGODB_URI).then(()=>{app.listen(process.env.PORT||3000,'0.0.0.0',()=>console.log('Server started'));}).catch(err=>{console.error(err);process.exit(1);});
